    /** 执行操作并在完成后更新界面。 */
    private <T> void runTask(String name, Supplier<T> work, Consumer<T> onDone) {
        if (busy) {
            return;
        }
        busy = true;
        updateButtons();
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));

        // 虚拟线程执行耗时操作，完成后切回 EDT 更新界面
        Thread.ofVirtual().name("ffm-" + name).start(() -> {
            T value = null;
            Throwable error = null;
            try {
                value = work.get();
            } catch (Throwable t) {
                error = t;
            }
            T produced = value;
            Throwable failure = error;
            SwingUtilities.invokeLater(() -> {
                busy = false;
                setCursor(Cursor.getDefaultCursor());
                updateButtons();
                if (failure != null) {
                    String detail = describe(failure);
                    log.failure(name + " 执行异常：" + detail);
                    showError(name + " 执行异常", detail);
                    return;
                }
                onDone.accept(produced);
            });
        });
    }

    private void updateButtons() {
        boolean editable = !readOnly && !busy;
        boolean hasSelection = table.getSelectedRow() >= 0;

        addButton.setEnabled(editable);
        clearFormButton.setEnabled(editable);
        refreshButton.setEnabled(!busy);
        deleteButton.setEnabled(editable && hasSelection);
        cleanupButton.setEnabled(editable);
        deleteAllButton.setEnabled(editable && tableModel.getRowCount() > 0);
        elevateButton.setEnabled(readOnly && !busy);

        typeCombo.setEnabled(editable);
        protocolCombo.setEnabled(editable);
        listenAddressCombo.setEnabled(editable);
        listenPortField.setEnabled(editable);
        connectAddressField.setEnabled(editable);
        connectPortField.setEnabled(editable);
        firewallCheck.setEnabled(editable);
        restrictRemoteCheck.setEnabled(editable && firewallCheck.isSelected());
    }

    private void showError(String title, String message) {
        JOptionPane.showMessageDialog(this, message, title, JOptionPane.ERROR_MESSAGE);
    }

    private static String describe(Throwable error) {
        String message = error.getMessage();
        return error.getClass().getSimpleName() + (message == null ? "" : "：" + message);
    }
