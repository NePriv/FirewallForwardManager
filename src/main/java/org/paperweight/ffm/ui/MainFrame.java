    private Optional<ForwardRule> readForm() {
        ProxyType type = selectedType();
        TransportProtocol protocol = (TransportProtocol) protocolCombo.getSelectedItem();
        String listenAddress = currentListenAddress();
        String connectAddress = connectAddressField.getText().strip();
        Integer listenPort = Ports.parse(listenPortField.getText());
        Integer connectPort = Ports.parse(connectPortField.getText());

        // netsh 把“监听所有地址”显示为 *，这里允许用户直接粘贴，并换算为该转发类型的显式通配地址
        if (listenAddress.equals("*") || listenAddress.equalsIgnoreCase("any")) {
            listenAddress = type.wildcardListenAddress();
        }

        if (listenAddress.isEmpty()) {
            return invalid("请填写监听地址（0.0.0.0 或 :: 表示监听本机所有地址）。");
        }
        if (!AddressValidator.matchesFamily(listenAddress, type.listenIpv6())) {
            return invalid("监听地址必须是合法的 " + (type.listenIpv6() ? "IPv6" : "IPv4")
                    + " 地址（当前转发类型为 " + type.displayName() + "）。");
        }
        if (listenPort == null || !Ports.isValid(listenPort)) {
            return invalid("监听端口必须是 " + Ports.describeRange() + " 之间的整数。");
        }
        if (connectAddress.isEmpty()) {
            return invalid("请填写转发目标地址。");
        }
        if (!AddressValidator.matchesFamily(connectAddress, type.connectIpv6())) {
            return invalid("转发目标地址必须是合法的 " + (type.connectIpv6() ? "IPv6" : "IPv4")
                    + " 地址（不能填域名）。");
        }
        if (connectPort == null || !Ports.isValid(connectPort)) {
            return invalid("转发端口必须是 " + Ports.describeRange() + " 之间的整数。");
        }
        return Optional.of(new ForwardRule(type, protocol, listenAddress, listenPort, connectAddress, connectPort));
    }

    private <T> Optional<T> invalid(String message) {
        JOptionPane.showMessageDialog(this, message, "输入有误", JOptionPane.WARNING_MESSAGE);
        return Optional.empty();
    }

    private String currentListenAddress() {
        Object edited = listenAddressCombo.getEditor().getItem();
        if (edited != null && !String.valueOf(edited).isBlank()) {
            return String.valueOf(edited).strip();
        }
        Object selected = listenAddressCombo.getSelectedItem();
        return selected == null ? "" : String.valueOf(selected).strip();
    }

