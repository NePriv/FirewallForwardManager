    private void refresh(boolean silent) {
        runTask("刷新转发列表", manager::snapshot, result -> {
            log.operation("刷新转发列表", result);
            if (!result.ok()) {
                statusLabel.setText("读取失败：" + result.message());
                if (!silent) {
                    showError("刷新失败", result.message());
                }
                return;
            }
            ForwardManager.Snapshot snapshot = result.value();
            managedFirewallRules = snapshot.managedFirewallRules();
            tableModel.setData(snapshot.entries(), snapshot.knownProtocols(), managedFirewallRules);
            statusLabel.setText(snapshot.entries().size() + " 条转发规则 · 本工具防火墙规则 "
                    + managedFirewallRules.size() + " 条 · 更新于 " + LocalTime.now().format(TIME_FORMAT));
            updateButtons();
        });
    }

    private void onAdd() {
        Optional<ForwardRule> parsed = readForm();
        if (parsed.isEmpty()) {
            return;
        }
        ForwardRule rule = parsed.get();
        boolean addFirewall = firewallCheck.isSelected();
        boolean restrictRemote = addFirewall && restrictRemoteCheck.isSelected();

        Optional<ProxyEntry> duplicate = tableModel.entries().stream()
                .filter(entry -> entry.type() == rule.type()
                        && entry.listenAddress().equalsIgnoreCase(rule.listenAddress())
                        && entry.listenPort() == rule.listenPort())
                .findFirst();

        if (duplicate.isPresent()) {
            ProxyEntry existing = duplicate.get();
            int answer = JOptionPane.showConfirmDialog(this,
                    "已存在监听 " + existing.listenEndpoint() + " 的 " + rule.type().displayName()
                            + " 转发（当前指向 " + existing.connectEndpoint() + "）。\n\n"
                            + "是否删除原规则并按新配置重建？",
                    "规则已存在", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (answer != JOptionPane.YES_OPTION) {
                return;
            }
            Set<String> rules = managedFirewallRules;
            runTask("覆盖转发规则", () -> manager.replace(existing, rules, rule, addFirewall, restrictRemote), result -> {
                log.operation("覆盖转发规则", result);
                if (!result.ok()) {
                    showError("覆盖失败", result.message());
                }
                refresh(true);
            });
            return;
        }

        runTask("添加转发规则", () -> manager.add(rule, addFirewall, restrictRemote), result -> {
            log.operation("添加转发规则", result);
            if (!result.ok()) {
                showError("添加失败", result.message());
            }
            refresh(true);
        });
    }

    private void onDeleteSelected() {
        int viewRow = table.getSelectedRow();
        if (viewRow < 0) {
            showError("删除转发", "请先在列表中选中一条规则。");
            return;
        }
        ProxyEntry entry = tableModel.entryAt(table.convertRowIndexToModel(viewRow));
        List<String> firewallNames = List.of(
                NetshCommands.firewallRuleName(TransportProtocol.TCP, entry.listenPort(), entry.listenAddress()),
                NetshCommands.firewallRuleName(TransportProtocol.UDP, entry.listenPort(), entry.listenAddress()));
        List<String> existingRules = firewallNames.stream().filter(managedFirewallRules::contains).toList();

        StringBuilder message = new StringBuilder("确认删除以下转发规则？\n\n")
                .append(entry.describe()).append("\n\n")
                .append("将执行：netsh interface portproxy delete ").append(entry.type().netshKeyword())
                .append(" listenport=").append(entry.listenPort())
                .append(" listenaddress=").append(entry.listenAddress())
                .append("\n协议：TCP 与 UDP 各尝试一次（转发列表不显示协议）");
        if (existingRules.isEmpty()) {
            message.append("\n（未发现对应的防火墙规则，无需清理）");
        } else {
            message.append("\n同时删除防火墙规则：").append(String.join("、", existingRules));
        }

        if (JOptionPane.showConfirmDialog(this, message.toString(), "确认删除",
                JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE) != JOptionPane.YES_OPTION) {
            return;
        }

        Set<String> rules = managedFirewallRules;
        runTask("删除转发规则", () -> manager.delete(entry, rules, true), result -> {
            log.operation("删除转发规则", result);
            if (!result.ok()) {
                showError("删除未完全成功", result.message());
            }
            refresh(true);
        });
    }

    private void onCleanupOrphans() {
        List<ProxyEntry> entries = tableModel.entries();
        Set<String> rules = managedFirewallRules;
        runTask("清理孤立防火墙规则", () -> manager.cleanupOrphanFirewallRules(entries, rules), result -> {
            log.operation("清理孤立防火墙规则", result);
            if (!result.ok()) {
                showError("清理孤立防火墙规则", result.message());
            } else if (result.countOrZero() > 0) {
                JOptionPane.showMessageDialog(this, result.message(), "清理完成", JOptionPane.INFORMATION_MESSAGE);
            }
            refresh(true);
        });
    }

    private void onDeleteAll() {
        List<ProxyEntry> entries = tableModel.entries();
        if (entries.isEmpty()) {
            showError("清空全部转发", "当前没有转发规则。");
            return;
        }
        int first = JOptionPane.showConfirmDialog(this,
                "将删除本机全部 " + entries.size() + " 条端口转发规则，并清理本工具创建的防火墙入站规则。\n"
                        + "此操作不可撤销，是否继续？",
                "清空全部转发", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (first != JOptionPane.YES_OPTION) {
            return;
        }
        int second = JOptionPane.showConfirmDialog(this,
                "二次确认：确认删除全部 " + entries.size() + " 条转发规则？",
                "二次确认", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (second != JOptionPane.YES_OPTION) {
            return;
        }

        Set<String> rules = managedFirewallRules;
        runTask("清空全部转发", () -> manager.deleteAll(entries, rules), result -> {
            log.operation("清空全部转发", result);
            if (!result.ok()) {
                showError("清空未完全成功", result.message());
            }
            refresh(true);
        });
    }

    private void onElevate() {
        log.info("正在请求管理员权限…");
        if (SelfRelauncher.relaunchElevated()) {
            dispose();
            System.exit(0);
        }
        showError("提权失败", "无法以管理员身份重启（可能取消了 UAC 提示）。\n"
                + "可以改为从管理员的终端或 IDE 启动本程序。");
    }

