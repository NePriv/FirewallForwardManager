    private void startupTasks() {
        log.info("程序启动：" + (readOnly ? "只读模式（未提权）" : "管理员模式")
                + "，命令输出按 UTF-8 自动识别（回退 " + runner.charset().name() + "）");
        refresh(true);
        if (readOnly) {
            helperLabel.setText("IP Helper：只读模式未检查");
        } else {
            runTask("检查 IP Helper 服务", ipHelper::ensureRunning, result -> {
                log.operation("检查 IP Helper 服务", result);
                helperLabel.setText(result.ok() ? "IP Helper：运行中" : "IP Helper：异常");
                if (!result.ok()) {
                    log.failure("IP Helper 服务未运行时，端口转发规则虽然存在但不会生效。");
                }
            });
        }
    }

    private void reloadListenAddresses() {
        if (listenAddressCombo.getItemCount() == 0) {
            listenAddressCombo.getEditor().setItem(selectedType().wildcardListenAddress());
        }
        Object previous = listenAddressCombo.isEditable() ? listenAddressCombo.getEditor().getItem() : null;
        ProxyType type = selectedType();

        listenAddressCombo.removeAllItems();
        listenAddressCombo.addItem(type.wildcardListenAddress());
        for (LocalAddresses.Address address : LocalAddresses.list()) {
            if (address.ipv6() == type.listenIpv6()) {
                listenAddressCombo.addItem(address.text());
            }
        }
        boolean previousStillUsable = previous != null
                && AddressValidator.matchesFamily(String.valueOf(previous), type.listenIpv6());
        listenAddressCombo.getEditor().setItem(previousStillUsable ? previous : type.wildcardListenAddress());
    }

    private ProxyType selectedType() {
        ProxyType type = (ProxyType) typeCombo.getSelectedItem();
        return type == null ? ProxyType.V4_TO_V4 : type;
    }

